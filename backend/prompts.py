def screen_question(style: str, instruction: str) -> str:
    output = {"brief": "请给出答案和简短解析。", "steps": "请给出答案及详细解题步骤。",
              "code": "请解答编程题，给出可运行代码、必要说明及时间和空间复杂度。"}[style]
    return "请识别并解答这张截图中的题目。" + output + ("\n用户补充要求：\n" + instruction if instruction else "")


def question_with_context(question: str, history: list[dict]) -> str:
    recent = []
    for item in history[-6:]:
        text = item.get("question", "").strip()
        # Even a cancelled/unanswered fragment can contain the topic or constraints.
        if text and not item.get("demo") and item.get("source") != "screen" and text not in question and text not in recent:
            recent.append(text[:1000])
    if not recent:
        return question
    return ("最近听到或手动补充的问题原文（从早到晚，仅用于联系话题）：\n"
            + json.dumps(recent, ensure_ascii=False)
            + "\n请结合相关限定条件理解下面的当前问题，直接回答当前问题。\n当前问题：\n" + question)


